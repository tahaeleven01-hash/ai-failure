"""
Mock Agent Adapter for AI Failure Museum.
Simulates deterministic agent execution for local testing and pipeline validation.
Clearly labeled as a mock double.
"""

from __future__ import annotations

import time
from enum import Enum
from pathlib import Path
from typing import List, Optional

from afm.adapters.base import AgentExecutionOutput, BaseAdapter


class MockBehavior(str, Enum):
    """Presets for mock agent behavior."""
    SUCCESS = "success"          # Produces valid fix
    FAIL = "fail"                # Fails task or crashes
    SYNTAX_ERROR = "syntax-error"  # Produces broken code
    TIMEOUT = "timeout"          # Simulates timeout
    NO_OP = "no-op"              # Makes no changes


class MockAdapter(BaseAdapter):
    """
    Mock adapter simulating agent behavior without external network access or LLM inference.
    """

    def __init__(self, behavior: MockBehavior = MockBehavior.SUCCESS, delay: float = 0.05):
        self._behavior = behavior
        self._delay = delay

    @property
    def name(self) -> str:
        return "mock"

    @property
    def is_mock(self) -> bool:
        return True

    @property
    def version(self) -> str:
        return "1.0.0-mock"

    def set_behavior(self, behavior: MockBehavior) -> None:
        self._behavior = behavior

    def run_agent(
        self,
        task_prompt: str,
        context: Optional[str],
        workspace_dir: Path,
        timeout_seconds: int = 120,
    ) -> AgentExecutionOutput:
        start_time = time.time()
        time.sleep(self._delay)

        if self._behavior == MockBehavior.TIMEOUT:
            time.sleep(min(timeout_seconds + 0.1, 0.5))
            return AgentExecutionOutput(
                exit_code=124,
                stdout="Mock agent execution timed out.",
                stderr="Agent timed out.",
                duration_seconds=time.time() - start_time,
                error_message="Execution exceeded timeout limit.",
            )

        if self._behavior == MockBehavior.FAIL:
            return AgentExecutionOutput(
                exit_code=1,
                stdout="[MOCK] Agent encountered an internal reasoning error.",
                stderr="Error: Unable to resolve dependencies.",
                duration_seconds=time.time() - start_time,
                error_message="Simulated agent failure.",
            )

        if self._behavior == MockBehavior.SYNTAX_ERROR:
            # Simulate bad edit
            broken_file = workspace_dir / "broken_solution.py"
            broken_file.write_text("def broken_func(:\n    pass\n", encoding="utf-8")
            return AgentExecutionOutput(
                exit_code=0,
                stdout="[MOCK] Modified broken_solution.py",
                stderr="",
                duration_seconds=time.time() - start_time,
                modified_files=["broken_solution.py"],
                diff="+ def broken_func(:\n+     pass\n",
            )

        if self._behavior == MockBehavior.NO_OP:
            return AgentExecutionOutput(
                exit_code=0,
                stdout="[MOCK] Task analyzed. No modifications required.",
                stderr="",
                duration_seconds=time.time() - start_time,
                modified_files=[],
            )

        # SUCCESS behavior
        solution_file = workspace_dir / "solution.py"
        solution_file.write_text(
            "# Verified solution generated by agent\ndef resolve_task():\n    return True\n",
            encoding="utf-8",
        )

        return AgentExecutionOutput(
            exit_code=0,
            stdout=f"[MOCK] Task '{task_prompt[:40]}' completed successfully.",
            stderr="",
            duration_seconds=time.time() - start_time,
            modified_files=["solution.py"],
            diff="+ def resolve_task():\n+     return True\n",
        )
